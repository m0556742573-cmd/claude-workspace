// The message texts after his round-9 notes: the approved set the consultant learns from.
const fs = require('fs');
const path = require('path');
const { rows } = require(path.join(__dirname, 'round9.js'));
const S = '[שם המציג], [העסק] · [טלפון]';
const QUIET = '[שם המציג] · [טלפון]';
const th = (line) => `שלום [שם],\nתודה שעצרת אצלנו בתערוכה. ${line}\n${S}`;
const swap = (id, label, fn) => { const r = rows.find((x) => x[0] === id && x[1] === label); fn(r); };
const drop = (id, label) => rows.splice(rows.findIndex((x) => x[0] === id && x[1] === label), 1);

swap(1, 'תודה שביקרת', (r) => { r[3] = th('כשתגיע השמחה, בשעה טובה — אשמח לעזור. וגם בחידוש שטריימל קיים.'); });
swap(2, 'הודעת המשך', (r) => { r[3] = r[3].replace('כחודשיים מראש', 'חודש מראש'); });
swap(13, 'הזמנה לאירוע', (r) => { r[3] = 'שלום [שם],\nאשמח להזמין אותך לשמוע אותי באחת החתונות הקרובות. אתאם עם המשפחה ואחזור אליך.\n' + S; });
drop(15, 'סרטון או הקלטה לדוגמה');
swap(33, 'תודה שביקרת', (r) => { r[3] = th('ושווה לזכור: אחרי תאונה עם צד ג\', אתה בוחר את המוסך.'); });
swap(44, 'הודעה לגבאי', (r) => { r[3] = 'שלום [שם],\nכמו שדיברנו: השבת מגיעה אליכם טעימה מהמאפים שלנו לקידוש. הנהג שלנו יביא אותה ביום שישי ב[שעה]. שבת שלום!\n' + S; });
swap(46, 'הזמנה ראשונה בהנחה', (r) => {
  r[1] = 'הזמנה ראשונה בהנחה (1 מ-3)'; r[2] = 'יום רביעי, בשבוע הראשון';
  r[3] = 'שלום [שם],\nלשבת הקרובה: ההזמנה הראשונה שלכם בהנחה של [הנחה]. מזמינים עד יום חמישי ב[שעה]: [טלפון או קישור].\n' + S;
});
const i46 = rows.findIndex((x) => x[0] === 46 && /1 מ-3/.test(x[1]));
rows.splice(i46 + 1, 0,
  [46, 'הזמנה ראשונה בהנחה (2 מ-3)', 'יום רביעי, בשבוע השני', 'שלום [שם],\nמה על השולחן השבת? [מנה או מוצר של השבוע]. ההנחה להזמנה הראשונה עדיין בתוקף.\n' + S],
  [46, 'הזמנה ראשונה בהנחה (3 מ-3)', 'יום רביעי, בשבוע השלישי', 'שלום [שם],\nזו הפעם האחרונה שאני מזכיר: ההנחה להזמנה הראשונה בתוקף עד יום חמישי. אחרי זה לא אטריח יותר.\n' + S]);
for (const id of [70, 75, 78, 79, 80, 81]) swap(id, 'תודה שביקרת', (r) => { r[3] = r[3].replace(S, QUIET); });
swap(84, 'רשימת התפוצה (דוגמה)', (r) => { r[2] = 'מדי פעם, רק למי שאמר בדוכן שהוא רוצה'; r[3] = r[3].replace(S, QUIET); });
swap(88, 'תודה שביקרת', (r) => { r[3] = th('לימודים מקצועיים, במסגרת שמתאימה לך.'); });
drop(100, 'תודה שביקרת');
swap(100, 'איך מזמינים', (r) => { r[2] = 'בערב של יום התערוכה (במקום התודה)'; });
swap(102, 'הודעת המשך', (r) => {
  r[1] = 'הודעת המשך — התאריך פנוי';
  r[2] = 'אחרי שבוע, אם אין תשובה ואתה סימנת שהתאריך פנוי';
  r[3] = 'שלום [שם],\nבדקתי את התאריך שביקשת, והדירה פנויה. כדאי לסגור מוקדם, לפני שמישהו אחר יתפוס.\n' + S;
});
const i102 = rows.findIndex((x) => x[0] === 102 && /פנוי$/.test(x[1]));
rows.splice(i102 + 1, 0, [102, 'הודעת המשך — התאריך תפוס', 'אחרי שבוע, אם אין תשובה ואתה סימנת שהתאריך תפוס', 'שלום [שם],\nבדקתי את התאריך שביקשת. הוא כבר תפוס, אבל יש לי חלופה קרובה: [תאריך או דירה]. מתאים?\n' + S]);

fs.writeFileSync(path.join(__dirname, 'messages-approved.json'), JSON.stringify(rows.map(([id, label, when, text]) => ({ id, label, when, text })), null, 1));
console.log('messages', rows.length, '| still with [העסק] in sensitive:', rows.filter((r) => [32, 70, 75, 78, 79, 80, 81, 84].includes(r[0]) && r[3].includes('[העסק]')).map((r) => r[0]));
